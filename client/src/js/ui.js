export const translateUI = (lang, strings) => {
  const s = strings[lang] || strings.en;
  const subtitleEl = document.getElementById('ui-subtitle');
  const profileTitleEl = document.getElementById('ui-profile-title');
  const ageLabelEl = document.getElementById('ui-label-age-sidebar');
  const locLabelEl = document.getElementById('ui-label-loc-sidebar');
  const statusLabelEl = document.getElementById('ui-label-status-sidebar');
  const saveBtnEl = document.getElementById('ui-save-profile');
  const signOutBtnEl = document.getElementById('ui-signout');
  const inputEl = document.getElementById('userInput');
  const modalTitleEl = document.getElementById('ui-modal-title');
  const modalDescEl = document.getElementById('ui-modal-desc');
  const modalSaveBtnEl = document.getElementById('ui-modal-save');

  if (subtitleEl) subtitleEl.textContent = s.subtitle;
  if (profileTitleEl) profileTitleEl.textContent = s.profileTitle;
  if (ageLabelEl) ageLabelEl.textContent = s.labelAge;
  if (locLabelEl) locLabelEl.textContent = s.labelLoc;
  if (statusLabelEl) statusLabelEl.textContent = s.labelStatus;
  if (saveBtnEl) saveBtnEl.textContent = s.btnSave;
  if (signOutBtnEl) signOutBtnEl.textContent = s.btnSignOut;
  if (inputEl) inputEl.placeholder = s.promptPlaceholder;
  if (modalTitleEl) modalTitleEl.textContent = s.modalTitle;
  if (modalDescEl) modalDescEl.textContent = s.modalDesc;
  if (modalSaveBtnEl) modalSaveBtnEl.textContent = s.modalBtn;
};

export const appendMessage = (role, content) => {
  const chat = document.getElementById('chat');
  const welcomeBanner = document.getElementById('welcome-banner');
  if (welcomeBanner) welcomeBanner.style.display = 'none';

  const row = document.createElement('div');
  row.className = `msg-row ${role}`;
  row.innerHTML = `
    <div class="avatar ${role}" aria-hidden="true">${role === 'ai' ? '🗳️' : '👤'}</div>
    <div class="bubble">${content}</div>
  `;
  chat.appendChild(row);
};

export const appendChips = (chips, isBusy, onChipClick) => {
  if (isBusy) return;
  const chat = document.getElementById('chat');
  const chipContainer = document.createElement('div');
  chipContainer.className = 'chip-container';
  chips.forEach(text => {
    const chip = document.createElement('button');
    chip.className = 'chip';
    chip.textContent = text;
    chip.setAttribute('aria-label', `Ask: ${text}`);
    chip.addEventListener('click', () => onChipClick(text));
    chipContainer.appendChild(chip);
  });
  chat.appendChild(chipContainer);
};

export const showTyping = () => {
  const chat = document.getElementById('chat');
  const row = document.createElement('div');
  row.id = 'typing-indicator';
  row.className = 'msg-row ai';
  row.innerHTML = `
    <div class="avatar ai">🗳️</div>
    <div class="bubble typing">
      <span></span><span></span><span></span>
    </div>
  `;
  chat.appendChild(row);
};

export const hideTyping = () => {
  const indicator = document.getElementById('typing-indicator');
  if (indicator) indicator.remove();
};

export const lockUI = (isBusy, sendBtn) => {
  if (sendBtn) sendBtn.disabled = isBusy;
  const userInput = document.getElementById('userInput');
  if (userInput) {
    userInput.disabled = isBusy;
    if (!isBusy) userInput.focus();
  }
};

export const autoResize = (textarea) => {
  if (!textarea) return;
  textarea.style.height = 'auto';
  textarea.style.height = textarea.scrollHeight + 'px';
};

